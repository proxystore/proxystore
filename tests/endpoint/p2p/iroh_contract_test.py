"""Tests of the iroh behavior which the peer manager depends on.

The bindings of iroh only expose some errors as strings, and the manager
patches private parts of the bindings. These tests use real iroh endpoints
so an upgrade of iroh which changes this behavior fails here with a message
which says what to update.
"""

