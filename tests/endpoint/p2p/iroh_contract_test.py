from testing.utils import wait_until


async def _ok(peer: EndpointId, request: Message) -> Message:
    return Message(Status.OK, b'')


@pytest.fixture
async def peers() -> AsyncGenerator[tuple[PeerManager, PeerManager], None]:
    manager1 = local_peer_manager()
    manager2 = local_peer_manager()
    await manager1.start(_ok)
    await manager2.start(_ok)
    connect_peers(manager1, manager2)
    yield manager1, manager2
    await manager1.close()
    await manager2.close()


async def test_unsupported_protocol_error(peers) -> None:
    manager1, manager2 = peers
    # The protocol (ALPN) of a newer version which the peer does not accept.
    with pytest.raises(iroh.IrohError) as exc_info:
        await manager1.endpoint.connect(
            manager2.addr(),
            alpn(PROTOCOL_VERSION + 1),
        )

    error = exc_info.value
    assert error.is_kind(iroh.IrohErrorKind.CONNECT)
    assert _unsupported_protocol(error), (
        'iroh changed the error raised when a peer does not accept the '
        f'protocol to {error.message()!r}. Update _unsupported_protocol() in '
        'proxystore/endpoint/p2p/manager.py.'
    )


@pytest.mark.parametrize('code', list(CloseCode))
async def test_close_reason_format(peers, code: CloseCode) -> None:
    manager1, manager2 = peers
    request = Message(Op.PING, Request(key=None).encode())
    await manager1.request(manager2.id, request)
    connection = manager1._preferred[manager2.id].connection

    # Closing the connection on one side gives the other side the code.
    manager2._close_peer(manager1.id, code, b'reason')
    await wait_until(lambda: connection.close_reason() is not None)

    reason = connection.close_reason()
    assert reason is not None
    others = [other for other in CloseCode if other != code]
    assert _closed_with(reason, code), (
        f'iroh changed the format of close reasons to {reason!r}. Update '
        '_closed_with() in proxystore/endpoint/p2p/manager.py.'
    )
    assert not any(_closed_with(reason, other) for other in others)


def test_bindings_patch_applies() -> None:
    # The bindings are patched when the manager is imported.
    import proxystore.endpoint.p2p.manager  # noqa: F401

    builder = getattr(iroh_ffi, '_UniffiRustBufferBuilder', None)
    assert builder is not None, (
        'The iroh bindings no longer have _UniffiRustBufferBuilder, so '
        'patch_buffer_write() in proxystore/endpoint/p2p/bindings.py does '
        'nothing. Remove it if the bindings were generated by uniffi 0.32.0 '
        'or newer, or update it otherwise.'
    )
    patched = builder.write is bindings._memmove_write
    assert patched or bindings._PER_BYTE_LOOP not in inspect.getsource(
        builder.write,
    ), (
        'The iroh bindings still copy bytes one at a time but were not '
        'patched. Update patch_buffer_write() in '
        'proxystore/endpoint/p2p/bindings.py.'
    )
